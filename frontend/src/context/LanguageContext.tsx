export const LANGUAGE_STORAGE_KEY = "specwise_lang";

export interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: Translations;
}

const defaultContextValue: LanguageContextType = {
  language: "en",
  setLanguage: () => {},
  t: english,
};

const LanguageContext = createContext<LanguageContextType>(defaultContextValue);

export function isLanguage(value: string | null | undefined): value is Language {
  return typeof value === "string" && (languages as readonly string[]).includes(value);
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");

  // Synchronize document lang attribute on client
  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = language;
    }
  }, [language]);

  // Read saved language from localStorage safely on mount
  useEffect(() => {
    try {
      if (typeof window !== "undefined" && window.localStorage) {
        const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
        if (isLanguage(saved)) {
          setLanguageState(saved);
        }
      }
    } catch {
      // Storage can be blocked in restricted/private browsing modes; defaults safely to "en".
    }
  }, []);

  const setLanguage = (lang: Language) => {
    const validLang: Language = isLanguage(lang) ? lang : "en";
    setLanguageState(validLang);
    try {
      if (typeof window !== "undefined" && window.localStorage) {
        window.localStorage.setItem(LANGUAGE_STORAGE_KEY, validLang);
      }
    } catch {
      // Retain in-memory state for session even if storage is restricted
    }
  };

  // Safe proxy that prevents Symbol/prototype crashes and provides English fallbacks
  const t = useMemo(() => {
    const activeDict = dictionary[language] ?? english;
    return new Proxy(activeDict, {
      get: (target, prop) => {
        if (typeof prop !== "string") {
          return Reflect.get(target, prop);
        }
        return target[prop] ?? english[prop] ?? prop;
      },
    });
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextType {
  return useContext(LanguageContext);
}
